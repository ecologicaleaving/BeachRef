-- Migration 007: Create New Tournament Schema
-- This migration implements the new tournament schema as specified in Story 2.1
-- Replaces the existing tournaments table with analytics-ready structure

-- =============================================================================
-- BACKUP AND DROP EXISTING TABLE
-- =============================================================================

-- Create backup of existing tournaments data
CREATE TABLE IF NOT EXISTS tournaments_backup AS 
SELECT * FROM tournaments;

-- Drop existing tournament table and its dependencies
DROP TABLE IF EXISTS tournaments CASCADE;

-- =============================================================================
-- NEW TOURNAMENT TABLE SCHEMA
-- =============================================================================

-- Create new tournaments table with proper normalization and analytics-ready structure
CREATE TABLE IF NOT EXISTS tournaments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vis_tournament_no bigint NOT NULL UNIQUE,   -- VIS: No
  tournament_code text NOT NULL UNIQUE,       -- VIS: Code
  name text NOT NULL,                         -- VIS: Title/Name
  country text,                               -- VIS: CountryCode
  city text,
  season int,                                 -- VIS: Season
  gender text CHECK (gender IN ('M','W')),
  type text,                                  -- Elite, Challenge, Futures...
  start_qualification date,
  start_main_draw date,
  status text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- =============================================================================
-- ANALYTICS-READY INDEXES
-- =============================================================================

-- Composite index for tournament filtering by season and gender
CREATE INDEX idx_tournaments_season_gender ON tournaments (season, gender);

-- Index for date-based queries
CREATE INDEX idx_tournaments_start_main_draw ON tournaments (start_main_draw);

-- Index for status filtering
CREATE INDEX idx_tournaments_status_new ON tournaments (status);

-- Index for geographic filtering
CREATE INDEX idx_tournaments_country ON tournaments (country);

-- Index for VIS tournament number lookups
CREATE INDEX idx_tournaments_vis_tournament_no ON tournaments (vis_tournament_no);

-- Index for tournament code lookups
CREATE INDEX idx_tournaments_tournament_code ON tournaments (tournament_code);

-- =============================================================================
-- ROW LEVEL SECURITY POLICIES
-- =============================================================================

-- Enable Row Level Security on tournaments table
ALTER TABLE tournaments ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if they exist
DROP POLICY IF EXISTS "anon_read" ON tournaments;
DROP POLICY IF EXISTS "service_upsert" ON tournaments;
DROP POLICY IF EXISTS "service_update" ON tournaments;

-- Create anon_read policy allowing public SELECT access
CREATE POLICY "anon_read" ON tournaments
FOR SELECT USING (true);

-- Create service_upsert policy for INSERT operations (service_role only)
CREATE POLICY "service_upsert" ON tournaments
FOR INSERT WITH CHECK (auth.role() = 'service_role');

-- Create service_update policy for UPDATE operations (service_role only)  
CREATE POLICY "service_update" ON tournaments
FOR UPDATE USING (auth.role() = 'service_role')
WITH CHECK (auth.role() = 'service_role');

-- Create service_delete policy for DELETE operations (service_role only)
CREATE POLICY "service_delete" ON tournaments
FOR DELETE USING (auth.role() = 'service_role');

-- =============================================================================
-- AUTOMATIC TIMESTAMP TRIGGERS
-- =============================================================================

-- Create or replace function to update timestamp on record changes
CREATE OR REPLACE FUNCTION update_tournaments_timestamp()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Create trigger for automatic timestamp updates
DROP TRIGGER IF EXISTS update_tournaments_timestamp_trigger ON tournaments;
CREATE TRIGGER update_tournaments_timestamp_trigger
  BEFORE UPDATE ON tournaments
  FOR EACH ROW
  EXECUTE FUNCTION update_tournaments_timestamp();

