-- =============================================================================
-- UPDATE MATCHES TABLE FOREIGN KEY (DEFENSIVE)
-- =============================================================================

-- Update matches table to reference new tournament structure
-- This section is defensive and handles cases where matches table may not exist
DO $$
BEGIN
  -- Check if matches table exists before attempting to modify it
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'matches') THEN
    -- Drop existing foreign key constraint if it exists
    EXECUTE 'ALTER TABLE matches DROP CONSTRAINT IF EXISTS matches_tournament_no_fkey';
    
    -- Check if tournament_no column exists in matches table
    IF EXISTS (
      SELECT 1 FROM information_schema.columns 
      WHERE table_name = 'matches' AND column_name = 'tournament_no'
    ) THEN
      -- Add new foreign key constraint referencing vis_tournament_no
      -- Note: This assumes matches.tournament_no contains VIS tournament numbers
      EXECUTE 'ALTER TABLE matches 
               ADD CONSTRAINT matches_tournament_vis_no_fkey 
               FOREIGN KEY (tournament_no) REFERENCES tournaments(vis_tournament_no) ON DELETE CASCADE';
      
      RAISE NOTICE 'Updated matches table foreign key constraint to reference tournaments.vis_tournament_no';
    ELSE
      RAISE WARNING 'matches table exists but tournament_no column not found - skipping foreign key constraint';
    END IF;
  ELSE
    RAISE NOTICE 'matches table does not exist yet - foreign key constraint will be added when matches table is created';
  END IF;
EXCEPTION
  WHEN OTHERS THEN
    RAISE WARNING 'Failed to update matches table foreign key: %', SQLERRM;
END $$;

-- =============================================================================
-- DATA VALIDATION FUNCTIONS
-- =============================================================================

-- Function to validate tournament data integrity
CREATE OR REPLACE FUNCTION validate_tournament_data()
RETURNS TABLE (
  validation_result text,
  record_count bigint,
  issue_description text
) AS $$
BEGIN
  -- Check for duplicate vis_tournament_no
  RETURN QUERY
  SELECT 
    'duplicate_vis_tournament_no'::text,
    COUNT(*)::bigint,
    'Duplicate VIS tournament numbers found'::text
  FROM tournaments 
  GROUP BY vis_tournament_no 
  HAVING COUNT(*) > 1;
  
  -- Check for duplicate tournament_code
  RETURN QUERY
  SELECT 
    'duplicate_tournament_code'::text,
    COUNT(*)::bigint,
    'Duplicate tournament codes found'::text
  FROM tournaments 
  GROUP BY tournament_code 
  HAVING COUNT(*) > 1;
  
  -- Check for invalid gender values
  RETURN QUERY
  SELECT 
    'invalid_gender'::text,
    COUNT(*)::bigint,
    'Invalid gender values found (not M or W)'::text
  FROM tournaments 
  WHERE gender IS NOT NULL AND gender NOT IN ('M', 'W');
  
  -- Check for missing required fields
  RETURN QUERY
  SELECT 
    'missing_required_fields'::text,
    COUNT(*)::bigint,
    'Records with missing vis_tournament_no, tournament_code, or name'::text
  FROM tournaments 
  WHERE vis_tournament_no IS NULL 
     OR tournament_code IS NULL 
     OR name IS NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Grant execute permissions to service role
GRANT EXECUTE ON FUNCTION validate_tournament_data() TO service_role;
GRANT EXECUTE ON FUNCTION update_tournaments_timestamp() TO service_role;

