-- Function to get sync status summary
CREATE OR REPLACE FUNCTION get_sync_status_summary()
RETURNS TABLE (
  total_syncs bigint,
  running_syncs bigint,
  completed_syncs bigint,
  failed_syncs bigint,
  last_successful_sync timestamptz,
  last_failed_sync timestamptz,
  average_sync_duration interval
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    COUNT(*)::bigint as total_syncs,
    COUNT(CASE WHEN ss.status = 'running' THEN 1 END)::bigint as running_syncs,
    COUNT(CASE WHEN ss.status = 'completed' THEN 1 END)::bigint as completed_syncs,
    COUNT(CASE WHEN ss.status = 'failed' THEN 1 END)::bigint as failed_syncs,
    MAX(CASE WHEN ss.status = 'completed' THEN ss.end_time END) as last_successful_sync,
    MAX(CASE WHEN ss.status = 'failed' THEN ss.end_time END) as last_failed_sync,
    AVG(
      CASE 
        WHEN ss.status IN ('completed', 'failed') AND ss.end_time IS NOT NULL 
        THEN ss.end_time - ss.start_time 
        ELSE NULL 
      END
    ) as average_sync_duration
  FROM sync_status ss;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to get recent sync performance metrics
CREATE OR REPLACE FUNCTION get_sync_performance_metrics(days_back integer DEFAULT 7)
RETURNS TABLE (
  sync_date date,
  total_syncs bigint,
  successful_syncs bigint,
  failed_syncs bigint,
  total_records_processed bigint,
  success_rate numeric,
  average_duration interval
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    DATE(ss.start_time) as sync_date,
    COUNT(*)::bigint as total_syncs,
    COUNT(CASE WHEN ss.status = 'completed' THEN 1 END)::bigint as successful_syncs,
    COUNT(CASE WHEN ss.status = 'failed' THEN 1 END)::bigint as failed_syncs,
    SUM(ss.records_processed)::bigint as total_records_processed,
    CASE 
      WHEN COUNT(*) > 0 THEN 
        ROUND(COUNT(CASE WHEN ss.status = 'completed' THEN 1 END) * 100.0 / COUNT(*), 2)
      ELSE 0
    END as success_rate,
    AVG(
      CASE 
        WHEN ss.status IN ('completed', 'failed') AND ss.end_time IS NOT NULL 
        THEN ss.end_time - ss.start_time 
        ELSE NULL 
      END
    ) as average_duration
  FROM sync_status ss
  WHERE ss.start_time >= CURRENT_DATE - INTERVAL '%s days' % days_back
  GROUP BY DATE(ss.start_time)
  ORDER BY sync_date DESC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to cleanup old sync status records
CREATE OR REPLACE FUNCTION cleanup_old_sync_status(days_to_keep integer DEFAULT 30)
RETURNS TABLE (
  deleted_count bigint,
  cleanup_timestamp timestamptz
) AS $$
DECLARE
  deleted_rows bigint;
BEGIN
  -- Delete sync status records older than specified days
  DELETE FROM sync_status 
  WHERE start_time < CURRENT_TIMESTAMP - INTERVAL '%s days' % days_to_keep;
  
  GET DIAGNOSTICS deleted_rows = ROW_COUNT;
  
  RETURN QUERY
  SELECT 
    deleted_rows as deleted_count,
    NOW() as cleanup_timestamp;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to get running sync details (for monitoring)
CREATE OR REPLACE FUNCTION get_running_sync_details()
RETURNS TABLE (
  sync_id text,
  start_time timestamptz,
  duration interval,
  records_processed bigint,
  sync_type text
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    ss.sync_id,
    ss.start_time,
    NOW() - ss.start_time as duration,
    ss.records_processed,
    ss.sync_type
  FROM sync_status ss
  WHERE ss.status = 'running'
  ORDER BY ss.start_time;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

