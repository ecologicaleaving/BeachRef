-- =============================================================================
-- SYNC STATUS TABLE SCHEMA
-- =============================================================================

-- Create sync_status table for monitoring synchronization operations
CREATE TABLE IF NOT EXISTS sync_status (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sync_id text NOT NULL UNIQUE,
  status text CHECK (status IN ('pending','running','completed','failed')) NOT NULL,
  start_time timestamptz NOT NULL,
  end_time timestamptz,
  records_processed bigint DEFAULT 0,
  errors text[] DEFAULT '{}',
  last_error text,
  sync_type text DEFAULT 'full', -- 'full', 'incremental', 'tournaments', 'matches', 'referees'
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

