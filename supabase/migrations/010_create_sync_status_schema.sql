-- Function to validate sync status data integrity
CREATE OR REPLACE FUNCTION validate_sync_status_data()
RETURNS TABLE (
  validation_result text,
  record_count bigint,
  issue_description text
) AS $$
BEGIN
  -- Check for duplicate sync_id
  RETURN QUERY
  SELECT 
    'duplicate_sync_id'::text,
    COUNT(*)::bigint,
    'Duplicate sync IDs found'::text
  FROM sync_status 
  GROUP BY sync_id 
  HAVING COUNT(*) > 1;
  
  -- Check for invalid status values
  RETURN QUERY
  SELECT 
    'invalid_status'::text,
    COUNT(*)::bigint,
    'Invalid status values found (not pending, running, completed, or failed)'::text
  FROM sync_status 
  WHERE status NOT IN ('pending', 'running', 'completed', 'failed');
  
  -- Check for missing required fields
  RETURN QUERY
  SELECT 
    'missing_required_fields'::text,
    COUNT(*)::bigint,
    'Records with missing sync_id, status, or start_time'::text
  FROM sync_status 
  WHERE sync_id IS NULL 
     OR status IS NULL 
     OR start_time IS NULL;
     
  -- Check for completed/failed syncs without end_time
  RETURN QUERY
  SELECT 
    'missing_end_time'::text,
    COUNT(*)::bigint,
    'Completed or failed syncs without end_time'::text
  FROM sync_status 
  WHERE status IN ('completed', 'failed') 
     AND end_time IS NULL;
     
  -- Check for syncs with end_time before start_time
  RETURN QUERY
  SELECT 
    'invalid_time_order'::text,
    COUNT(*)::bigint,
    'Syncs with end_time before start_time'::text
  FROM sync_status 
  WHERE end_time IS NOT NULL 
     AND end_time < start_time;
     
  -- Check for long-running syncs (>1 hour)
  RETURN QUERY
  SELECT 
    'long_running_syncs'::text,
    COUNT(*)::bigint,
    'Syncs running for more than 1 hour (possible stuck processes)'::text
  FROM sync_status 
  WHERE status = 'running' 
     AND start_time < NOW() - INTERVAL '1 hour';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

