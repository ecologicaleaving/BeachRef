-- Function to validate match schema data integrity
CREATE OR REPLACE FUNCTION validate_match_schema_data()
RETURNS TABLE (
  validation_result text,
  record_count bigint,
  issue_description text
) AS $$
BEGIN
  -- Check for duplicate vis_event_no
  RETURN QUERY
  SELECT 
    'duplicate_vis_event_no'::text,
    COUNT(*)::bigint,
    'Duplicate VIS event numbers found'::text
  FROM events 
  GROUP BY vis_event_no 
  HAVING COUNT(*) > 1;
  
  -- Check for duplicate vis_match_no
  RETURN QUERY
  SELECT 
    'duplicate_vis_match_no'::text,
    COUNT(*)::bigint,
    'Duplicate VIS match numbers found'::text
  FROM matches 
  GROUP BY vis_match_no 
  HAVING COUNT(*) > 1;
  
  -- Check for invalid gender values in events
  RETURN QUERY
  SELECT 
    'invalid_gender_events'::text,
    COUNT(*)::bigint,
    'Invalid gender values found in events (not M or W)'::text
  FROM events 
  WHERE gender IS NOT NULL AND gender NOT IN ('M', 'W');
  
  -- Check for missing required fields in events
  RETURN QUERY
  SELECT 
    'missing_required_fields_events'::text,
    COUNT(*)::bigint,
    'Events with missing vis_event_no or tournament_id'::text
  FROM events 
  WHERE vis_event_no IS NULL OR tournament_id IS NULL;
  
  -- Check for missing required fields in matches
  RETURN QUERY
  SELECT 
    'missing_required_fields_matches'::text,
    COUNT(*)::bigint,
    'Matches with missing vis_match_no, tournament_code, or event_id'::text
  FROM matches 
  WHERE vis_match_no IS NULL OR tournament_code IS NULL OR event_id IS NULL;
  
  -- Check for invalid referee roles
  RETURN QUERY
  SELECT 
    'invalid_referee_roles'::text,
    COUNT(*)::bigint,
    'Invalid referee roles found (not FIRST, SECOND, or CHALLENGE)'::text
  FROM match_referees 
  WHERE role NOT IN ('FIRST', 'SECOND', 'CHALLENGE');
  
  -- Check for orphaned matches (event_id not in events)
  RETURN QUERY
  SELECT 
    'orphaned_matches'::text,
    COUNT(*)::bigint,
    'Matches with event_id not found in events table'::text
  FROM matches m
  WHERE NOT EXISTS (SELECT 1 FROM events e WHERE e.id = m.event_id);
  
  -- Check for orphaned match_referees (match_id not in matches)
  RETURN QUERY
  SELECT 
    'orphaned_match_referees'::text,
    COUNT(*)::bigint,
    'Match referees with match_id not found in matches table'::text
  FROM match_referees mr
  WHERE NOT EXISTS (SELECT 1 FROM matches m WHERE m.id = mr.match_id);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

