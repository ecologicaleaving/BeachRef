-- Create events table with tournament relationship and VIS compatibility
CREATE TABLE IF NOT EXISTS events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vis_event_no bigint NOT NULL,
  event_code text,
  tournament_id bigint NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
  gender text CHECK (gender IN ('M','W')),
  phase text,                    -- Qualification, Main Draw, Finals
  name text,
  country text,
  start_date date,
  end_date date,
  status text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  UNIQUE (tournament_id, gender, phase)
);

-- Create index for events table
CREATE INDEX idx_events_tournament_phase ON events (tournament_id, phase);
CREATE INDEX idx_events_vis_event_no ON events (vis_event_no);
CREATE INDEX idx_events_status ON events (status);

-- =============================================================================
-- MATCHES TABLE SCHEMA
-- =============================================================================

-- Create matches table with proper normalization for sets and team data
CREATE TABLE IF NOT EXISTS matches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vis_match_no bigint NOT NULL UNIQUE,
  tournament_code text NOT NULL,            -- VIS: TournamentCode (lookup veloce)
  event_id bigint NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  round_code text,
  round_name text,
  round_phase text,
  utc_datetime timestamptz,
  local_datetime timestamptz,
  court text,
  team_a_name text,
  team_b_name text,
  team_a_fed text,
  team_b_fed text,
  team_a_players bigint[],
  team_b_players bigint[],
  sets jsonb DEFAULT '[]',                  -- [{a:21,b:19}, ...]
  result jsonb,                             -- {resultType, winnerRank, ...}
  status text,
  are_court_and_time_published boolean,
  nb_live_score_upload int,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Create indexes for matches table
CREATE INDEX idx_matches_event_id ON matches (event_id);
CREATE INDEX idx_matches_tournament_code ON matches (tournament_code);
CREATE INDEX idx_matches_status ON matches (status);
CREATE INDEX idx_matches_vis_match_no ON matches (vis_match_no);
