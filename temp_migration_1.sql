-- Function for match statistics by tournament
CREATE OR REPLACE FUNCTION get_match_statistics_by_tournament(tournament_code_param text)
RETURNS TABLE (
  total_matches bigint,
  completed_matches bigint,
  active_matches bigint,
  upcoming_matches bigint,
  completion_rate numeric
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    COUNT(*)::bigint as total_matches,
    COUNT(CASE WHEN m.status = 'completed' THEN 1 END)::bigint as completed_matches,
    COUNT(CASE WHEN m.status = 'active' THEN 1 END)::bigint as active_matches,
    COUNT(CASE WHEN m.status = 'upcoming' THEN 1 END)::bigint as upcoming_matches,
    CASE 
      WHEN COUNT(*) > 0 THEN 
        ROUND(COUNT(CASE WHEN m.status = 'completed' THEN 1 END) * 100.0 / COUNT(*), 2)
      ELSE 0
    END as completion_rate
  FROM matches m
  WHERE m.tournament_code = tournament_code_param;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function for referee assignment counts
CREATE OR REPLACE FUNCTION get_referee_assignment_counts(referee_id_param bigint)
RETURNS TABLE (
  total_assignments bigint,
  first_referee_count bigint,
  second_referee_count bigint,
  challenge_referee_count bigint
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    COUNT(*)::bigint as total_assignments,
    COUNT(CASE WHEN mr.role = 'FIRST' THEN 1 END)::bigint as first_referee_count,
    COUNT(CASE WHEN mr.role = 'SECOND' THEN 1 END)::bigint as second_referee_count,
    COUNT(CASE WHEN mr.role = 'CHALLENGE' THEN 1 END)::bigint as challenge_referee_count
  FROM match_referees mr
  WHERE mr.referee_id = referee_id_param;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function for match results aggregation
CREATE OR REPLACE FUNCTION get_match_results_aggregation(event_id_param bigint)
RETURNS TABLE (
  total_matches bigint,
  matches_with_results bigint,
  straight_set_wins bigint,
  three_set_matches bigint,
  average_match_duration interval
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    COUNT(*)::bigint as total_matches,
    COUNT(CASE WHEN m.result IS NOT NULL THEN 1 END)::bigint as matches_with_results,
    COUNT(CASE WHEN jsonb_array_length(m.sets) = 2 THEN 1 END)::bigint as straight_set_wins,
    COUNT(CASE WHEN jsonb_array_length(m.sets) = 3 THEN 1 END)::bigint as three_set_matches,
    AVG(
      CASE 
        WHEN m.local_datetime IS NOT NULL AND m.utc_datetime IS NOT NULL 
        THEN m.local_datetime - m.utc_datetime 
        ELSE NULL 
      END
    ) as average_match_duration
  FROM matches m
  WHERE m.event_id = event_id_param;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function for performance-optimized common queries
CREATE OR REPLACE FUNCTION get_matches_by_tournament_and_date(
  tournament_code_param text,
  start_date_param date,
  end_date_param date
)
RETURNS TABLE (
  match_id bigint,
  vis_match_no bigint,
  event_id bigint,
  round_name text,
  utc_datetime timestamptz,
  court text,
  team_a_name text,
  team_b_name text,
  status text,
  referee_count bigint
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    m.id as match_id,
    m.vis_match_no,
    m.event_id,
    m.round_name,
    m.utc_datetime,
    m.court,
    m.team_a_name,
    m.team_b_name,
    m.status,
    COUNT(mr.referee_id)::bigint as referee_count
  FROM matches m
  LEFT JOIN match_referees mr ON m.id = mr.match_id
  WHERE m.tournament_code = tournament_code_param
    AND DATE(m.utc_datetime) BETWEEN start_date_param AND end_date_param
  GROUP BY m.id, m.vis_match_no, m.event_id, m.round_name, m.utc_datetime, 
           m.court, m.team_a_name, m.team_b_name, m.status
  ORDER BY m.utc_datetime;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

