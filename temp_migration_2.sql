-- Function to validate analytics data integrity
CREATE OR REPLACE FUNCTION validate_analytics_data()
RETURNS TABLE (
  validation_type text,
  issue_count bigint,
  description text
) AS $$
BEGIN
  -- Check for orphaned referee_analytics records
  RETURN QUERY
  SELECT 
    'orphaned_referee_analytics'::text,
    COUNT(*)::bigint,
    'Referee analytics records with referee_id not found in referees table'::text
  FROM referee_analytics ra
  WHERE NOT EXISTS (SELECT 1 FROM referees r WHERE r.id = ra.referee_id);
  
  -- Check for analytics events without required fields
  RETURN QUERY
  SELECT 
    'invalid_analytics_events'::text,
    COUNT(*)::bigint,
    'Analytics events missing event_type or with invalid event_data'::text
  FROM analytics_events 
  WHERE event_type IS NULL OR event_type = '';
  
  -- Check for negative assignment counts
  RETURN QUERY
  SELECT 
    'negative_assignment_counts'::text,
    COUNT(*)::bigint,
    'Referee analytics with negative assignment counts'::text
  FROM referee_analytics 
  WHERE total_assignments < 0 OR first_referee_count < 0 OR second_referee_count < 0 OR challenge_referee_count < 0;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to cleanup old analytics data based on retention policy
CREATE OR REPLACE FUNCTION cleanup_old_analytics_data()
RETURNS TABLE (
  cleanup_type text,
  records_deleted bigint
) AS $$
DECLARE
  deleted_events bigint;
  deleted_analytics bigint;
BEGIN
  -- Delete analytics events older than 90 days (detailed data retention)
  DELETE FROM analytics_events 
  WHERE timestamp < (now() - INTERVAL '90 days');
  GET DIAGNOSTICS deleted_events = ROW_COUNT;
  
  -- Delete referee analytics older than 2 years (aggregated data retention)
  DELETE FROM referee_analytics 
  WHERE created_at < (now() - INTERVAL '2 years');
  GET DIAGNOSTICS deleted_analytics = ROW_COUNT;
  
  RETURN QUERY VALUES
    ('analytics_events'::text, deleted_events),
    ('referee_analytics'::text, deleted_analytics);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

