-- Create referees table if it doesn't exist (referenced by referee_analytics)
CREATE TABLE IF NOT EXISTS referees (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vis_referee_no text UNIQUE,
  first_name text,
  last_name text,
  federation_code text,
  level text,
  gender text CHECK (gender IN ('M','F')),
  experience_years int,
  status text CHECK (status IN ('ACTIVE','INACTIVE','SUSPENDED')),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Create referee_analytics table for aggregated metrics
CREATE TABLE IF NOT EXISTS referee_analytics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referee_id bigint REFERENCES referees(id),
  date date NOT NULL,
  total_assignments int DEFAULT 0,
  first_referee_count int DEFAULT 0,
  second_referee_count int DEFAULT 0,
  challenge_referee_count int DEFAULT 0,
  tournaments_worked text[],
  performance_score decimal(5,2),
  created_at timestamptz DEFAULT now(),
  UNIQUE(referee_id, date)
);

-- Create event tracking table for client-side analytics
CREATE TABLE IF NOT EXISTS analytics_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type text NOT NULL, -- 'referee_view', 'assignment_action', 'match_monitor'
  user_context jsonb,
  event_data jsonb,
  timestamp timestamptz DEFAULT now()
);

