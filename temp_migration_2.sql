-- Function to update referee analytics when match_referees changes
CREATE OR REPLACE FUNCTION update_referee_analytics_on_assignment()
RETURNS TRIGGER AS $$
DECLARE
  ref_id bigint;
  match_date date;
  tournament_codes text[];
BEGIN
  -- Get referee_id and match date from the trigger
  IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
    ref_id := NEW.referee_id;
    -- Get match date from matches table
    SELECT DATE(m.utc_datetime), ARRAY_AGG(DISTINCT m.tournament_code)
    INTO match_date, tournament_codes
    FROM matches m
    WHERE m.id = NEW.match_id
    GROUP BY DATE(m.utc_datetime);
  ELSIF TG_OP = 'DELETE' THEN
    ref_id := OLD.referee_id;
    -- Get match date from matches table
    SELECT DATE(m.utc_datetime), ARRAY_AGG(DISTINCT m.tournament_code)
    INTO match_date, tournament_codes
    FROM matches m
    WHERE m.id = OLD.match_id
    GROUP BY DATE(m.utc_datetime);
  END IF;

  -- Update or create analytics record
  INSERT INTO referee_analytics (referee_id, date, tournaments_worked)
  VALUES (ref_id, match_date, tournament_codes)
  ON CONFLICT (referee_id, date)
  DO UPDATE SET
    tournaments_worked = COALESCE(referee_analytics.tournaments_worked, ARRAY[]::text[]) || COALESCE(tournament_codes, ARRAY[]::text[]),
    updated_at = now();

  -- Recalculate assignment counts for this referee and date
  UPDATE referee_analytics SET
    total_assignments = (
      SELECT COUNT(*)
      FROM match_referees mr
      JOIN matches m ON mr.match_id = m.id
      WHERE mr.referee_id = ref_id AND DATE(m.utc_datetime) = match_date
    ),
    first_referee_count = (
      SELECT COUNT(*)
      FROM match_referees mr
      JOIN matches m ON mr.match_id = m.id
      WHERE mr.referee_id = ref_id AND mr.role = 'FIRST' AND DATE(m.utc_datetime) = match_date
    ),
    second_referee_count = (
      SELECT COUNT(*)
      FROM match_referees mr
      JOIN matches m ON mr.match_id = m.id
      WHERE mr.referee_id = ref_id AND mr.role = 'SECOND' AND DATE(m.utc_datetime) = match_date
    ),
    challenge_referee_count = (
      SELECT COUNT(*)
      FROM match_referees mr
      JOIN matches m ON mr.match_id = m.id
      WHERE mr.referee_id = ref_id AND mr.role = 'CHALLENGE' AND DATE(m.utc_datetime) = match_date
    )
  WHERE referee_id = ref_id AND date = match_date;

  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger on match_referees table for assignment tracking
DROP TRIGGER IF EXISTS trigger_update_referee_analytics ON match_referees;
CREATE TRIGGER trigger_update_referee_analytics
  AFTER INSERT OR UPDATE OR DELETE ON match_referees
  FOR EACH ROW
  EXECUTE FUNCTION update_referee_analytics_on_assignment();

-- Function to update analytics when matches change
CREATE OR REPLACE FUNCTION update_analytics_on_match_change()
RETURNS TRIGGER AS $$
BEGIN
  -- Insert analytics event for match changes
  INSERT INTO analytics_events (event_type, event_data)
  VALUES (
    'match_update',
    jsonb_build_object(
      'match_id', COALESCE(NEW.id, OLD.id),
      'tournament_code', COALESCE(NEW.tournament_code, OLD.tournament_code),
      'status_change', CASE 
        WHEN TG_OP = 'UPDATE' AND OLD.status != NEW.status THEN 
          jsonb_build_object('from', OLD.status, 'to', NEW.status)
        ELSE NULL
      END,
      'operation', TG_OP
    )
  );

  -- Trigger recalculation of affected referee analytics if match datetime changed
  IF TG_OP = 'UPDATE' AND (OLD.utc_datetime != NEW.utc_datetime OR OLD.tournament_code != NEW.tournament_code) THEN
    -- Update all referee analytics for referees assigned to this match
    UPDATE referee_analytics 
    SET tournaments_worked = (
      SELECT ARRAY_AGG(DISTINCT m.tournament_code)
      FROM match_referees mr
      JOIN matches m ON mr.match_id = m.id
      WHERE mr.referee_id = referee_analytics.referee_id 
        AND DATE(m.utc_datetime) = referee_analytics.date
    )
    WHERE referee_id IN (
      SELECT referee_id FROM match_referees WHERE match_id = NEW.id
    ) AND date = DATE(NEW.utc_datetime);
  END IF;

  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger on matches table for performance data collection
DROP TRIGGER IF EXISTS trigger_analytics_match_change ON matches;
CREATE TRIGGER trigger_analytics_match_change
  AFTER INSERT OR UPDATE OR DELETE ON matches
  FOR EACH ROW
  EXECUTE FUNCTION update_analytics_on_match_change();

